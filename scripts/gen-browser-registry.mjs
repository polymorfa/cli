// Generate the actual command inventory; local-only commands get rejecting loaders.
import console from 'node:console'
import {URL, fileURLToPath} from 'node:url'
import {readFileSync, readdirSync, statSync, writeFileSync} from 'node:fs'
import {join, relative} from 'node:path'
import {format, resolveConfig} from 'prettier'
import ts from 'typescript'

const root = fileURLToPath(new URL('../src/commands/', import.meta.url))
const policyPath = fileURLToPath(
  new URL('../src/browser/command-support.ts', import.meta.url),
)
const parsed = ts.createSourceFile(
  policyPath,
  readFileSync(policyPath, 'utf8'),
  ts.ScriptTarget.Latest,
  true,
)
const declaration = parsed.statements
  .filter(ts.isVariableStatement)
  .flatMap((statement) => [...statement.declarationList.declarations])
  .find(
    (value) =>
      ts.isIdentifier(value.name) && value.name.text === 'UNSUPPORTED_COMMANDS',
  )
if (
  !declaration?.initializer ||
  !ts.isObjectLiteralExpression(declaration.initializer)
)
  throw new Error('Browser command policy must be a literal object')
const unsupported = new Map()
for (const property of declaration.initializer.properties) {
  if (
    !ts.isPropertyAssignment(property) ||
    !ts.isStringLiteral(property.name) ||
    !ts.isStringLiteral(property.initializer) ||
    !property.initializer.text
  )
    throw new Error(
      'Browser command policy must contain string IDs and reasons',
    )
  unsupported.set(property.name.text, property.initializer.text)
}
const files = []
const walk = (directory) => {
  for (const name of readdirSync(directory).sort()) {
    const path = join(directory, name)
    if (statSync(path).isDirectory()) walk(path)
    else if (
      name.endsWith('.ts') &&
      !name.endsWith('.test.ts') &&
      !name.endsWith('.d.ts')
    )
      files.push(path)
  }
}
walk(root)
const ids = new Set()
const entries = files.map((file) => {
  const rel = relative(root, file).replaceAll('\\', '/').replace(/\.ts$/, '')
  const id = rel.split('/').join(' ')
  ids.add(id)
  const reason = unsupported.get(id)
  return (
    '  ' +
    JSON.stringify(id) +
    ': ' +
    (reason
      ? '() => Promise.reject(new BrowserUnsupportedError(' +
        JSON.stringify(reason) +
        '))'
      : "() => import('../commands/" + rel + ".js')") +
    ','
  )
})
for (const id of unsupported.keys())
  if (!ids.has(id))
    throw new Error('Unsupported command is absent from real inventory: ' + id)
const out =
  '// Generated by scripts/gen-browser-registry.mjs. Do not edit.\n' +
  "import {BrowserUnsupportedError} from './stubs/unsupported.js'\n" +
  'export const COMMAND_LOADERS: Readonly<Record<string, () => Promise<{default: unknown}>>> = {\n' +
  entries.join('\n') +
  '\n}\n'
const target = new URL('../src/browser/registry.gen.ts', import.meta.url)
const options = (await resolveConfig(fileURLToPath(target))) ?? {}
writeFileSync(
  target,
  await format(out, {...options, filepath: fileURLToPath(target)}),
)
console.log(
  'registry: ' +
    files.length +
    ' commands; ' +
    unsupported.size +
    ' local/unsupported loaders excluded',
)
