// Writes src/browser/registry.gen.ts: every command id mapped to a lazy import of its module.
// A command's id is its path under src/commands, with directories joined by spaces.
import console from 'node:console'
import {URL} from 'node:url'
import {readdirSync, statSync, writeFileSync} from 'node:fs'
import {join, relative} from 'node:path'
import {format, resolveConfig} from 'prettier'

const root = new URL('../src/commands/', import.meta.url).pathname
const files = []
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) walk(path)
    else if (
      name.endsWith('.ts') &&
      !name.endsWith('.test.ts') &&
      !name.endsWith('.d.ts')
    )
      files.push(path)
  }
}
walk(root)
const entries = files.map((file) => {
  const rel = relative(root, file).replace(/\.ts$/, '')
  const id = rel.split('/').join(' ')
  return `  ${JSON.stringify(id)}: () => import('../commands/${rel}.js'),`
})
const out = `// Generated by scripts/gen-browser-registry.mjs. Do not edit.
export const COMMAND_LOADERS: Readonly<Record<string, () => Promise<{default: unknown}>>> = {
${entries.join('\n')}
}
`
const target = new URL('../src/browser/registry.gen.ts', import.meta.url)
// Formatted like the rest of the source, so the format check passes.
const options = (await resolveConfig(target.pathname)) ?? {}
writeFileSync(
  target,
  await format(out, {...options, filepath: target.pathname}),
)
console.log(`registry: ${files.length} commands`)
